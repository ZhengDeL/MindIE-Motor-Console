class IdentityV1(Protocol):
    settings: Any  # secure_cookie: bool, bootstrap_token: str; no public secrets
    clock: Callable[[], float]
    sso_status: dict
    session_cookie_name: str
    def bind_security(self, session, policy) -> None: ...
    def setup_required(self) -> bool: ...
    def transaction(self, *, write=False) -> ContextManager[UnitOfWork]: ...
    def authenticate(self, request, *, required=True): ...
    def authorize(self, request, allowed_roles=frozenset({"admin", "operator", "viewer"}), *, csrf=True, account_only=False): ...
    def bootstrap(self, request, response, *, username, password, display_name="") -> dict: ...
    def login(self, request, response, username, password) -> dict: ...
    def users(self, request) -> dict: ...
    def create_user(self, request, *, username, password, display_name="", role="viewer") -> dict: ...
    def update_user(self, request, user_id, *, role=None, disabled=None, display_name=None, delete=False, new_password=None) -> dict: ...
    def change_password(self, request, response, current_password, new_password) -> dict: ...
    def federated_login(self, request, response, *, issuer, subject, display_name, role="viewer") -> dict: ...
    def check_origin(self, request) -> None: ...
    def csrf(self, raw: str) -> str: ...
    def clear_cookie(self, response) -> None: ...
    def revoke_session(self, unit, token_hash) -> None: ...
    def security_event(self, unit, actor, action, target, status="success", *, target_snapshot=None) -> Any: ...
    def throttle(self, request, account) -> None: ...


class StorageV1(Protocol):
    directory: Path
    schema_version: int
    def unit_of_work(self, *, write=False) -> ContextManager[UnitOfWork]: ...
    def get(self, kind, identifier) -> dict | None: ...
    def list(self, kind) -> list[dict]: ...
    def put(self, kind, value, *, revision=False) -> None: ...
    def put_many(self, records) -> None: ...
    def delete(self, kind, identifier) -> None: ...
    def page(self, kind, *, limit=100, offset=0, filters=None) -> dict: ...
    def revisions(self, service_id) -> list[dict]: ...
    def health(self) -> dict: ...
    def storage_info(self) -> dict: ...
    def mutate_many_audited(self, records: Iterable[tuple[str, dict]], *, action: str, target: str,
                            status: str = "success", detail: str = "", metadata: dict | None = None,
                            deletes: Iterable[tuple[str, str]] | None = None,
                            revision_keys: set[tuple[str, str]] | None = None) -> dict: ...
    def mutate_audited(self, kind: str, identifier: str, value: dict | None, *, action: str,
                       detail: str = "", metadata: dict | None = None, revision: bool = False,
                       target: str | None = None, status: str = "success", expected_revision: int | None = None) -> dict: ...
    def compare_and_mutate_audited(self, kind: str, identifier: str, expected: dict, value: dict, *,
                                   action: str, target: str, detail: str = "", metadata: dict | None = None,
                                   guards: Iterable[tuple[str, str, dict]] | None = None) -> bool: ...
    def audit(self, action: str, target: str, status: str, detail: str = "", *, actor: Any = None,
              request_id: str | None = None, metadata: dict | None = None,
              connection: UnitOfWork | None = None) -> dict: ...
    def query_audit(self, *, limit: int = 100, offset: int = 0, **filters: Any) -> dict: ...
    def audit_items(self, limit: int = 250) -> list[dict]: ...
    def prune_audit(self, *, before: str, keep_latest: int = 1000, dry_run: bool = True) -> dict: ...

    def backup(self, destination_dir, *, reason="manual") -> dict: ...
    def close(self) -> None: ...


