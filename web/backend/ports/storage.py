"""Backend-neutral persistence values and failure contracts.

No driver, SQLAlchemy connection, database row or SQL string crosses this port.
"""
from __future__ import annotations

from collections.abc import Iterator, Mapping
from typing import Any, Protocol


class StorageError(RuntimeError):
    """A safe, backend-independent error suitable for operational reporting."""


class StorageUnavailable(StorageError):
    pass


class SchemaVersionError(StorageError):
    pass


class LeaseLost(StorageUnavailable):
    pass


class DuplicateIdentity(StorageError):
    pass


class RevisionConflict(StorageError):
    pass


class Record(Mapping):
    """Immutable public data record, independent of the selected SQL driver."""
    def __init__(self, values: Mapping[str, Any]):
        self._values = dict(values)
        self._ordered = tuple(values.values())

    def __getitem__(self, key):
        return self._ordered[key] if isinstance(key, int) else self._values[key]

    def __iter__(self) -> Iterator[str]:
        return iter(self._values)

    def __len__(self):
        return len(self._values)


class Records:
    """Materialized bounded repository query result; never keeps a cursor open."""
    def __init__(self, values=(), *, rowcount: int = 0):
        self._values = [Record(value) for value in values]
        self._offset = 0
        self.rowcount = rowcount

    def fetchone(self):
        if self._offset >= len(self._values):
            return None
        result = self._values[self._offset]
        self._offset += 1
        return result

    def fetchall(self):
        values = self._values[self._offset:]
        self._offset = len(self._values)
        return values

    def __iter__(self):
        return iter(self.fetchall())


class ResourceRepository(Protocol):
    def get(self, kind: str, identifier: str) -> dict | None: ...
    def list(self, kind: str) -> list[dict]: ...
    def page(self, kind: str, *, limit: int = 100, offset: int = 0,
             filters: dict[str,str] | None = None) -> dict: ...
    def put(self, kind: str, value: dict, *, revision: bool = False) -> None: ...
    def delete(self, kind: str, identifier: str) -> None: ...
    def compare_and_replace(self, kind: str, identifier: str, expected: dict,
                            value: dict, *, revision: bool = False) -> bool: ...


class AccountRepository(Protocol):
    def exists_any(self) -> Records: ...
    def get_user(self, user_id: str) -> Records: ...
    def get_username(self, username: str) -> Records: ...
    def list_users(self) -> Records: ...
    def create_user(self, user_id: str, username: str, display_name: str, password_hash: str | None,
                    role: str, created_at: float, updated_at: float, auth_source: str) -> Records: ...
    def update_user(self, role: str, disabled: int, display_name: str, password_hash: str | None,
                    updated_at: float, user_id: str) -> Records: ...
    def update_password(self, password_hash: str, updated_at: float, user_id: str) -> Records: ...
    def delete_user(self, user_id: str) -> Records: ...
    def get_admin_status(self, user_id: str) -> Records: ...
    def count_active_admins(self) -> Records: ...
    def count_active_local_admins(self) -> Records: ...
    def has_local_admin(self) -> Records: ...
    def remove_expired_throttles(self, cutoff: float) -> Records: ...
    def get_throttle(self, bucket: str) -> Records: ...
    def increment_throttle(self, bucket: str) -> Records: ...
    def reset_throttle(self, bucket: str, window_start: float) -> Records: ...
    def prune_expired_sessions(self, now: float, idle_cutoff: float) -> Records: ...
    def create_session(self, token_hash: str, user_id: str, auth_version: int,
                       created_at: float, last_seen: float, expires_at: float) -> Records: ...
    def trim_user_sessions(self, user_id: str) -> Records: ...
    def get_session_account(self, token_hash: str) -> Records: ...
    def get_session_window(self, token_hash: str) -> Records: ...
    def touch_session(self, last_seen: float, token_hash: str) -> Records: ...
    def revoke_session(self, token_hash: str) -> Records: ...
    def revoke_user_sessions(self, user_id: str) -> Records: ...
    def has_session(self, token_hash: str) -> Records: ...
    def get_federated_user(self, issuer: str, subject: str) -> Records: ...
    def bind_identity(self, issuer: str, subject: str, user_id: str) -> Records: ...
    def delete_identities(self, user_id: str) -> Records: ...
    def set_role(self, role: str, updated_at: float, user_id: str) -> Records: ...
    def set_display(self, display_name: str, updated_at: float, user_id: str) -> Records: ...
    def public_names(self, identifiers: list[str]) -> dict[str,dict]: ...


class OIDCRepository(Protocol):
    def create(self, state_hash: str, browser_hash: str, verifier: str, nonce: str,
                created_at: float, expires_at: float) -> Records: ...
    def get(self, state_hash: str) -> Records: ...
    def consume(self, state_hash: str) -> Records: ...
    def remove_expired(self, cutoff: float) -> Records: ...


class AuditRepository(Protocol):
    def append(self, value: dict, *, target_snapshot: dict | None = None) -> dict: ...
    def query(self, **filters) -> dict: ...
    def prune(self, *, before: str, keep_latest: int = 1000, dry_run: bool = True) -> dict: ...


class UnitOfWork(Protocol):
    resources: ResourceRepository
    accounts: AccountRepository
    oidc: OIDCRepository
    audit: AuditRepository


class DatabasePlugin(Protocol):
    name: str
    schema_version: int
    def unit_of_work(self, *, write: bool = False): ...
    def health(self) -> dict: ...
    def info(self) -> dict: ...
    def schema_info(self) -> dict: ...
    def backup(self, destination_dir, *, reason: str = 'manual') -> dict: ...
    def restore_snapshot(self, database_path, manifest_path=None) -> dict: ...
    def close(self) -> None: ...
